import java.io.*;
import java.net.*;

public class MeshNode {
    // 7830: Port mapped conceptually to the 7.83 Hz baseline resonance
    private static final int MESH_PORT = 7830; 
    private volatile boolean isRunning = true;

    // ==========================================
    // 0 RECEIVE: THE LISTENING ORBIT
    // ==========================================
    public void startListeningOrbit() {
        new Thread(() -> {
            try (ServerSocket serverSocket = new ServerSocket(MESH_PORT)) {
                System.out.println("[SYSTEM SOVEREIGNTY] Node Active. Listening on port " + MESH_PORT);
                
                while (isRunning) {
                    Socket incomingSocket = serverSocket.accept();
                    processIncomingPayload(incomingSocket);
                }
            } catch (IOException e) {
                System.err.println("[FLUX ERROR] Listener disrupted: " + e.getMessage());
            }
        }).start();
    }

    private void processIncomingPayload(Socket socket) {
        new Thread(() -> {
            try (
                BufferedReader in = new BufferedReader(new InputStreamReader(socket.getInputStream()));
                PrintWriter out = new PrintWriter(socket.getOutputStream(), true)
            ) {
                String sourceIp = socket.getInetAddress().getHostAddress();
                String payload = in.readLine();
                
                System.out.println("\n[0 RECEIVE] Payload captured from " + sourceIp);
                System.out.println("DATA: " + payload);
                
                // Ground the connection: Return the baseline invariant
                out.println("ACK_1=1");
            } catch (IOException e) {
                System.err.println("[FLUX ERROR] Payload read failed: " + e.getMessage());
            }
        }).start();
    }

    // ==========================================
    // 1 SEND: THE TRANSMISSION GATE
    // ==========================================
    public void executeTransmission(String targetIp, String payloadData) {
        new Thread(() -> {
            try (
                Socket socket = new Socket(targetIp, MESH_PORT);
                PrintWriter out = new PrintWriter(socket.getOutputStream(), true);
                BufferedReader in = new BufferedReader(new InputStreamReader(socket.getInputStream()))
            ) {
                System.out.println("\n[1 SEND] Transmitting to " + targetIp);
                out.println(payloadData);
                
                // Wait for the recipient to ground the connection
                String response = in.readLine();
                System.out.println("[LOOP CLOSED] Target returned: " + response);
            } catch (IOException e) {
                System.err.println("[FLUX ERROR] Gate failure to " + targetIp + ": " + e.getMessage());
            }
        }).start();
    }

    public static void main(String[] args) {
        MeshNode node = new MeshNode();
        
        // 1. Initialize the passive state (Open the Containment Bottle)
        node.startListeningOrbit();

        // 2. Simulate the Flux: Allow hardware to spin up
        try {
            Thread.sleep(1500);
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
        }

        // 3. Initiate the active state (The Microcosmic Orbit)
        // In full deployment, "127.0.0.1" is replaced by the IP string generated by the Subnet Discovery Engine
        String targetNodeIp = "127.0.0.1"; 
        String testPayload = "TESSERACT_GRASP_INITIATED // ETHICAL_FLOOR_VERIFIED";
        
        node.executeTransmission(targetNodeIp, testPayload);
    }
}