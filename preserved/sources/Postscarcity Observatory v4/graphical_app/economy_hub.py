"""Stateful page controls for three supplied local economic display engines."""
import copy
import hashlib
import json
import time
from economy_engines import PROFILES, validate
from sources import now, save_json


class EconomyHub:
    def __init__(self, rt):
        self.rt=rt
        self.path=rt.data/'economy-hub.json'
        self.log_path=rt.data/'work/economy-telemetry.jsonl'
        self.log_path.parent.mkdir(parents=True,exist_ok=True)
        try:saved=json.loads(self.path.read_text(encoding='utf-8'))
        except (OSError,ValueError):saved={}
        if not isinstance(saved,dict):saved={}
        self.rows={};self.last={};self.errors={};self.previous_hash=''
        for kind,profile in PROFILES.items():
            row=saved.get(kind,{})
            if not isinstance(row,dict):row={}
            override=rt.overrides.get(profile['module'],{})
            if not isinstance(override,dict):override={}
            try:inputs=validate(kind,row.get('inputs',override.get('module_input',profile['default_inputs'])))
            except ValueError:inputs=copy.deepcopy(profile['default_inputs'])
            self.rows[kind]={'inputs':inputs,'running':bool(row.get('running',False)),
                             'cycles':int(row.get('cycles',0)),'last_result':row.get('last_result'),
                             'history':row.get('history',[])[-120:]}
            rt.overrides[profile['module']]={'module_input':copy.deepcopy(inputs)}

    def owns(self, name):
        return any(profile['module']==name for profile in PROFILES.values())

    def save(self):
        save_json(self.path,self.rows)

    def view(self):
        with self.rt.lock:
            return {'engines':[{**copy.deepcopy(PROFILES[k]),**copy.deepcopy(row),'id':k,
                                'busy':PROFILES[k]['module'] in self.rt.inflight,'error':self.errors.get(k),
                                'status':self.rt.modules.get(PROFILES[k]['module'],{}).get('status','missing')}
                               for k,row in self.rows.items()],
                    'global_running':self.rt.config['running'], 'interval_seconds':2.5,
                    'log_path':str(self.log_path),
                    'scope':'Local calculations and file receipts. All economic metrics are generated by the supplied algorithms; no financial service is connected.'}

    def command(self, body):
        action=body.get('action');selected=body.get('engine')
        keys=list(self.rows) if selected=='all' else [selected]
        if action not in ('save','run','start','pause','reset') or any(k not in self.rows for k in keys):raise ValueError('Choose an engine and save, run, start, pause or reset')
        pending=[]
        with self.rt.lock:
            if action in ('save','reset') and any(PROFILES[k]['module'] in self.rt.inflight for k in keys):raise ValueError('Wait for the current cycle before editing or resetting')
            if action=='save':
                if len(keys)!=1:raise ValueError('Save inputs for one engine at a time')
                inputs=validate(keys[0],body.get('inputs'))
                self.rows[keys[0]]['inputs']=inputs
                self.rt.overrides[PROFILES[keys[0]]['module']]={'module_input':copy.deepcopy(inputs)}
            for key in keys:
                row=self.rows[key];name=PROFILES[key]['module']
                if action=='reset':
                    previous=row['inputs'];row['inputs']=copy.deepcopy(PROFILES[key]['default_inputs'])
                    for field in ('payload','target','random_seed'):row['inputs'][field]=previous[field]
                    row.update(running=False,cycles=0,last_result=None)
                    self.rt.overrides[name]={'module_input':copy.deepcopy(row['inputs'])}
                if action in ('start','pause'):row['running']=action=='start'
                if action in ('run','start'):
                    self.last[key]=time.monotonic();pending.append(name)
            self.save()
            for name in pending:self.rt.schedule(name)
        return self.view()

    def record(self, name, result):
        """Called under the runtime lock before the worker releases its slot."""
        key=next((k for k,p in PROFILES.items() if p['module']==name),None)
        if key is None:return
        output=result.get('reports',{}).get('module_result')
        if not result.get('ok') or not isinstance(output,dict):
            self.errors[key]=result.get('error','No module result');return
        try:
            inputs=validate(key,output['next_input'])
            row=self.rows[key];row['inputs']=inputs;row['last_result']=copy.deepcopy(output);row['cycles']+=1
            self.rt.overrides[name]={'module_input':copy.deepcopy(inputs)}
            receipt={'timestamp':now(),'engine':key,'cycle':row['cycles'],'worker_pid':result.get('pid'),
                     'primary_cascade':result.get('primary_cascade'), 'result':output,'previous_sha256':self.previous_hash}
            raw=json.dumps(receipt,sort_keys=True,ensure_ascii=False,allow_nan=False)
            receipt['sha256']=hashlib.sha256(raw.encode('utf-8')).hexdigest()
            # Local append-only usage, not a claim of cryptographic immutability.
            with self.log_path.open('a',encoding='utf-8') as stream:stream.write(json.dumps(receipt,ensure_ascii=False)+'\n')
            self.previous_hash=receipt['sha256']
            row['history']=(row['history']+[{'timestamp':receipt['timestamp'],'cycle':row['cycles'],
                'state':output['state'],'metrics':output['metrics'],'sha256':receipt['sha256']}])[-120:]
            self.errors.pop(key,None);self.save()
        except (OSError,ValueError,KeyError) as exc:self.errors[key]='Result recording failed: '+str(exc)

    def loop(self):
        while not self.rt.stop.is_set():
            with self.rt.lock:
                if self.rt.config['running']:
                    for key,row in self.rows.items():
                        name=PROFILES[key]['module']
                        if row['running'] and name not in self.rt.inflight and time.monotonic()-self.last.get(key,0)>=2.5:
                            self.last[key]=time.monotonic();self.rt.schedule(name)
            self.rt.stop.wait(.1)
